import json
from crewai import Crew, Agent, Task, Process, LLM
import agentops
import os
from tavily import TavilyClient
from scrapegraph_py import ScrapeGraphAI
from dotenv import load_dotenv
from pydantic import BaseModel, Field
from crewai.tools import tool

load_dotenv()

agentops.init(
    os.environ.get("AGENTOPS_API_KEY")
    
)

tavily_client = TavilyClient(api_key=os.environ.get("TAVILY_API_KEY"))

scrapegraph = ScrapeGraphAI(
    api_key=os.environ.get("SCRAPGRAPH_API_KEY")
)

llm = LLM(
    model="openai/openai/gpt-oss-120b",
    base_url="https://api.groq.com/openai/v1",
    api_key=os.environ.get("GROQ_API_KEY"),
    temperature=0
)


os.makedirs("agent-output", exist_ok=True)

#Agent 1-->Search Recommendation Agent
no_keywords = 3

search_agent = Agent(
    role="Search Recommendation Agent",
    goal="""To provide a list of suggested search queries.
    The queries must be varied, specific, relevant to the topic,
    phrased as questions, written in English, concise, and clear.""",
    backstory="""You are an experienced search strategist skilled at
    understanding user intent, identifying useful keywords, and creating
    diverse queries for different search angles. You prioritize relevance,
    clarity, and avoiding redundant queries.""",
    llm=llm,
    verbose=False
)


class SearchQueryOutput(BaseModel):
    queries: list[str] = Field(
        ...,
        description="List of generated search queries",
        min_length=1,
        max_length=3
    )



search_agent_task = Task(
    name="Search Query Generation",
    description="\n".join([
        "Rankyx is looking to buy {product_name} at the best prices (value-for-money strategy).",
        "The company targets these websites: {websites_list}",
        "The company wants to discover products online to compare them in a later stage.",
        "The stores must sell the product in {country_name}.",
        "Generate at most {no_keywords} queries.",
        "Write queries in {language}.",
        "Queries should target ecommerce product pages, not blogs or category pages.",
        "Search keywords could mention specific brand ,types,and technology of the product.",
        "Avoid near-duplicate queries; each must target a different angle."
    ]),
    expected_output=(
        "A structured JSON object containing a list of "
        "relevant ecommerce search queries."
    ),
    output_pydantic=SearchQueryOutput,
    output_file="agent-output/search_queries.json",
    agent=search_agent
)


#Agent 2-->Search Engine Agent

class SingleSearchResult(BaseModel):
    title: str = Field(..., min_length=1)
    url: str = Field(..., min_length=1)
    content: str = Field(..., min_length=1)
    score: float = Field(..., ge=0, le=1)   # ge/le OK here (a number)
    search_query: str = Field(..., min_length=1)

class SearchEngineOutput(BaseModel):
    search_results: list[SingleSearchResult] = Field(
        ...,
        description="List of search results for each query",
        min_length=1,
        max_length=3
    )

@tool
def search_engine_tool(query:str):
    """
        this tool is used to perform searches using the queries generated by the Search Recommendation Agent.
    """
    response=tavily_client.search(
        query=query,
        max_results=3
    )

    return str(response.get("results", []))
    
search_engine_agent = Agent(
    role="Search Engine Agent",
    goal="""
    To perform searches using the queries generated by the Search Recommendation Agent.
    The agent should retrieve relevant product listings from the specified websites,
""",
    backstory="""You are a skilled search engine agent with expertise in navigating various ecommerce platforms.""",
    llm=llm,
    verbose=True,
    tools=[search_engine_tool]
)

search_engine_task=Task(
    name="Search Engine Task",
    description="""The task is to search for the product using the queries generated by the Search Recommendation Agent and retrieve relevant product listings from the specified websites . 
    The agent should ensure that the results are accurate, relevant, and up-to-date.
    ignore any suspicious or irrelevant results and focus on providing the most useful information for the user.
    ignore any search results with confidence score less than {score_threshold}.,
    the search results will be used to compare the products in a later stage, so the agent should prioritize finding listings that provide detailed product information, including specifications, features, and pricing.
    """,
    expected_output="A structured JSON object containing the search results for each query.",
    output_pydantic=SearchEngineOutput,
    output_file="agent-output/search_engine_results.json",
    agent=search_engine_agent
)


#Agent 3---> Scraping Agent
class ProductSpecs(BaseModel):
    spec_name: str
    spec_value: str

class SingleExtractedProduct(BaseModel):
    page_url: str = Field(..., min_length=1)
    product_title: str = Field(..., min_length=1)
    product_url: str = Field(..., min_length=1)
    product_image_url: str | None = None
    product_current_price: float = Field(..., gt=0)
    product_original_price: float | None = Field(default=None, gt=0)
    product_discount_percentage: float | None = Field(default=None, ge=0, le=100)
    product_specs: list[ProductSpecs] = Field(..., min_length=1, max_length=3)
    agent_recommendation_rank: int = Field(..., ge=1)
    agent_recommendation_notes: list[str] = Field(default_factory=list, min_length=1)

class AllExtractedProducts(BaseModel):
    products: list[SingleExtractedProduct] = Field(..., min_length=1)

@tool
def scraping_tool(url: str) -> str:
    """Extract product information from one ecommerce product page."""

    result = scrapegraph.extract(
        prompt=(
            "Extract product title, product URL, image URL, current price, "
            "original price, discount percentage, and up to 3 specifications. "
            "Do not invent missing values."
        ),
        url=url,
        schema=SingleExtractedProduct.model_json_schema()
    )

    return json.dumps({
        "page_url": url,
        "details": result.data
    }, default=str)


scraping_agent=Agent(
    role="Scraping Agent",  
    goal=""" Extract product information by calling scraping_tool with exactly one
    argument named url, containing one product page URL per call.
    Never use page_url as the tool argument name.
    Do not invent missing product information.""",
    backstory="""You are an expert web research and data extraction specialist working within an AI-powered multi-agent system. You understand web page structures, search engine results, HTML content, structured metadata, pagination, and common website layouts.
    You know how to distinguish useful information from advertisements, navigation menus, duplicated content, and irrelevant text. You prioritize data accuracy, source traceability, and responsible scraping practices.
    You never invent missing information, treat search snippets as verified facts, or claim that you successfully scraped a website when you could not access its content.""",
    llm=llm,
    verbose=False,
    tools=[scraping_tool]
) 

scraping_task=Task(
    name="Scraping Task",
    description="\n".join([
        "The task is to extract product details from any ecommerce store page url.",
        "The task has to collect results from multiple pages urls.",
        "Collect the best {top_recommendations_no} products from the search results.",
    ]),
    expected_output="A structured JSON object containing the extracted product information from the scraped product listings.",
    output_pydantic=AllExtractedProducts,
    output_file="agent-output/scraping_results.json",
    agent=scraping_agent
)


#Agent 4--> Report Agent

report_agent = Agent(
    role="Report Generation Agent",
    goal="""
        Generate a professional HTML page containing a product analysis
        report using the structured product information returned by
        the Scraping Agent.
    """,

    backstory="""
        You are a skilled HTML report designer specializing in product
        comparison and data presentation. You transform structured product
        data into clean, responsive HTML reports using well-organized
        sections, comparison tables, product cards, and clear recommendations.
        You preserve data accuracy, highlight important findings, and never
        invent missing information.
    """,

    llm=llm,
    verbose=False
)


report_task = Task(
    name="Report Generation Task",

    description="""
        Generate a complete, standalone HTML report using the product data
        returned by the Scraping Agent.

        Include an executive summary, product comparison table, key
        specifications, price analysis, advantages and disadvantages,
        evidence-based recommendations, and data limitations.

        Use clean, responsive HTML and CSS with a professional layout.
        Use CSS and the Bootstrap framework for a better-looking page.

        Include source links where available, clearly identify missing
        information, and never fabricate product details.

        Return the complete HTML document, including <!DOCTYPE html>,
        <html>, <head>, embedded CSS, and <body>. Do not return JSON
        or Markdown.
    """,

    expected_output=(
        "A complete, standalone HTML report styled with CSS and Bootstrap, "
        "ready to open in a web browser."
    ),

    context=[scraping_task],#context of the report task is the output of the scraping task
    output_file="agent-output/product_report.html",
    agent=report_agent
)
#==============================
#             Run Crew
#==============================
crew = Crew(
    agents=[search_agent, search_engine_agent,scraping_agent, report_agent],
    tasks=[search_agent_task, search_engine_task, scraping_task, report_task],
    process=Process.sequential,
    verbose=True
)

crew_results = crew.kickoff(
    inputs={
        "product_name": "iPhone 14",
        "websites_list": ", ".join(["Amazon", "eBay", "Walmart"]),
        "country_name": "Egypt",
        "no_keywords": no_keywords,
        "language": "English",
        "score_threshold": 0.5,
        "top_recommendations_no": 5
    }
)

