from config import tavily_client
from crewai.tools import tool
import json
@tool
def search_engine_tool(query:str):
    """
        this tool is used to perform searches using the queries generated by the Search Recommendation Agent.
    """
    response=tavily_client.search(
        query=query,
        max_results=3
    )

    results = response.get("results", [])

    compact_results = [
        {
            "url": r.get("url"),
            "title": r.get("title"),
            "content": r.get("content", "")[:500],
            "score": r.get("score"),
        }
        for r in results
    ]

    return json.dumps(compact_results)
